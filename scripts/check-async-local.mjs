import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";

const base = process.env.API_URL ?? "http://localhost:8787";
if (!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(base)) throw new Error("Esta prueba crea datos y solo admite el runtime local.");
const id = randomUUID();
const token = randomBytes(32).toString("hex");
const headers = {"Content-Type":"application/json",Authorization:`Bearer ${token}`,Origin:"http://localhost:5175"};
const body = JSON.stringify({archivos:{"mundo.json":"{}","pedidos.json":'[{"id":1,"x":2,"y":3,"peso":1}]',"vehiculos.json":'[{"id":"V1"}]'},opciones:{iteraciones:0}});
let response = await fetch(`${base}/api/trabajos/${id}`,{method:"PUT",headers,body});
assert.equal(response.status,202,await response.text());
response = await fetch(`${base}/api/trabajos/${id}`,{method:"PUT",headers,body});
assert.equal(response.status,202,await response.text());
response = await fetch(`${base}/api/trabajos/${id}`,{headers:{...headers,Authorization:`Bearer ${randomBytes(32).toString("hex")}`}});
assert.equal(response.status,404);
response = await fetch(`${base}/api/trabajos/${id}`,{method:"PUT",headers,body:body.replace('"iteraciones":0','"iteraciones":1')});
assert.equal(response.status,409);
let state;
const deadline = Date.now() + 30_000;
do {
  response = await fetch(`${base}/api/trabajos/${id}`,{headers});
  assert.equal(response.status,200);
  state = await response.json();
  if(state.estado === "completado" && state.aviso !== "pendiente") break;
  assert.notEqual(state.estado,"fallido");
  await new Promise(resolve=>setTimeout(resolve,200));
} while(Date.now()<deadline);
assert.equal(state.estado,"completado");
assert.equal(state.aviso,"sin_suscripcion");
const result = await fetch(`${base}/api/trabajos/${id}/resultado`,{headers});
assert.equal(result.status,200);
assert.equal((await result.json()).evaluacion.metricas.entregados,1);
assert.equal(result.headers.get("cache-control"),"no-store");
response = await fetch(`${base}/api/trabajos/${randomUUID()}`,{method:"PUT",headers:{...headers,Origin:"https://otro.example"},body});
assert.equal(response.status,403);
response = await fetch(`${base}/api/trabajos/${id}`);
assert.equal(response.status,401);
response = await fetch(`${base}/api/push/config`);
assert.equal(response.status,200);
assert.ok((await response.json()).publicKey);
console.log("PASS runtime Cloudflare: 202, workflow real, idempotencia, aislamiento, CORS, persistencia y recuperación del resultado sin push.");
